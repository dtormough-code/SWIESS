import os
import sqlite3
import psycopg
from dotenv import load_dotenv

load_dotenv()

DATABASE_URL = os.getenv("DATABASE_URL")

if not DATABASE_URL:
    raise ValueError("DATABASE_URL is missing from your .env file")

# Read the existing SQLite database
sqlite_conn = sqlite3.connect("data.db")
sqlite_conn.row_factory = sqlite3.Row

categories = sqlite_conn.execute(
    "SELECT id, name FROM categories"
).fetchall()

notes = sqlite_conn.execute(
    """SELECT id, title, content, created_at, category_id,
              summary, study_questions
       FROM notes"""
).fetchall()

print(f"Found {len(categories)} categories and {len(notes)} notes.")

try:
    with psycopg.connect(DATABASE_URL) as pg_conn:
        with pg_conn.cursor() as cur:

            cur.execute("""
                CREATE TABLE IF NOT EXISTS categories (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name TEXT NOT NULL
                )
            """)

            cur.execute("""
                CREATE TABLE IF NOT EXISTS notes (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    title TEXT NOT NULL,
                    content TEXT,
                    created_at TEXT DEFAULT CURRENT_TIMESTAMP,
                    category_id BIGINT REFERENCES categories(id)
                        ON DELETE SET NULL,
                    summary TEXT,
                    study_questions TEXT
                )
            """)

            for category in categories:
                cur.execute("""
                    INSERT INTO categories (id, name)
                    VALUES (%s, %s)
                    ON CONFLICT (id) DO NOTHING
                """, (category["id"], category["name"]))

            for note in notes:
                cur.execute("""
                    INSERT INTO notes (
                        id, title, content, created_at,
                        category_id, summary, study_questions
                    )
                    VALUES (%s, %s, %s, %s, %s, %s, %s)
                    ON CONFLICT (id) DO NOTHING
                """, tuple(note))

            for table in ("categories", "notes"):
                cur.execute("""
                    SELECT setval(
                        pg_get_serial_sequence(%s, 'id'),
                        COALESCE((SELECT MAX(id) FROM """ + table + """), 1),
                        EXISTS (SELECT 1 FROM """ + table + """)
                    )
                """, (table,))

    print("Migration completed successfully.")

except Exception as error:
    print("Migration failed:", error)
    raise

finally:
    sqlite_conn.close()
